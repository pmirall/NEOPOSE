#!/usr/bin/env python3
"""What `npx cap sync android` does for this app, without Node: copy app/ into the Android assets and write the
files Capacitor generates. Used by the release build and by F-Droid, so both build the APK the same way
(reproducible builds) and F-Droid can use Debian's Node, which is older than the one the Capacitor CLI wants.
If a Capacitor plugin is added or removed, update PLUGINS (and capacitor.settings.gradle / capacitor.build.gradle)."""
import json, os, shutil

H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(H, 'android')
MAIN = os.path.join(A, 'app', 'src', 'main')
PLUGINS = [
    {'pkg': '@capacitor/filesystem', 'classpath': 'com.capacitorjs.plugins.filesystem.FilesystemPlugin'},
    {'pkg': '@capacitor/share', 'classpath': 'com.capacitorjs.plugins.share.SharePlugin'},
]

CORDOVA_BUILD = '''ext {
    androidxAppCompatVersion = project.hasProperty('androidxAppCompatVersion') ? rootProject.ext.androidxAppCompatVersion : '1.7.1'
    cordovaAndroidVersion = project.hasProperty('cordovaAndroidVersion') ? rootProject.ext.cordovaAndroidVersion : '14.0.1'
}

buildscript {
    repositories {
        google()
        mavenCentral()
    }
    dependencies {
        classpath 'com.android.tools.build:gradle:8.13.0'
    }
}

apply plugin: 'com.android.library'

android {
    namespace = "capacitor.cordova.android.plugins"
    compileSdk = project.hasProperty('compileSdkVersion') ? rootProject.ext.compileSdkVersion : 36
    defaultConfig {
        minSdkVersion project.hasProperty('minSdkVersion') ? rootProject.ext.minSdkVersion : 24
        targetSdkVersion project.hasProperty('targetSdkVersion') ? rootProject.ext.targetSdkVersion : 36
        versionCode 1
        versionName "1.0"
    }
    lintOptions {
        abortOnError = false
    }
    compileOptions {
        sourceCompatibility JavaVersion.VERSION_21
        targetCompatibility JavaVersion.VERSION_21
    }
}

repositories {
    google()
    mavenCentral()
    flatDir{
        dirs 'src/main/libs', 'libs'
    }
}

dependencies {
    implementation fileTree(dir: 'src/main/libs', include: ['*.jar'])
    implementation "androidx.appcompat:appcompat:$androidxAppCompatVersion"
    implementation "org.apache.cordova:framework:$cordovaAndroidVersion"
    // SUB-PROJECT DEPENDENCIES START

    // SUB-PROJECT DEPENDENCIES END
}

// PLUGIN GRADLE EXTENSIONS START
apply from: "cordova.variables.gradle"
// PLUGIN GRADLE EXTENSIONS END

for (def func : cdvPluginPostBuildExtras) {
    func()
}'''
CORDOVA_VARIABLES = '''// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN
ext {
  cdvMinSdkVersion = project.hasProperty('minSdkVersion') ? rootProject.ext.minSdkVersion : 24
  // Plugin gradle extensions can append to this to have code run at the end.
  cdvPluginPostBuildExtras = []
  cordovaConfig = [:]
}'''
CORDOVA_MANIFEST = '''<?xml version='1.0' encoding='utf-8'?>
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
xmlns:amazon="http://schemas.amazon.com/apk/res/android">
<application  >

</application>

</manifest>'''
CONFIG_XML = ("<?xml version='1.0' encoding='utf-8'?>\n"
              '<widget version="1.0.0" xmlns="http://www.w3.org/ns/widgets" xmlns:cdv="http://cordova.apache.org/ns/1.0">\n'
              '  <access origin="*" />\n  \n  \n</widget>')


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def main():
    cfg = json.load(open(os.path.join(H, 'capacitor.config.json'), encoding='utf-8'))
    pub = os.path.join(MAIN, 'assets', 'public')
    shutil.rmtree(pub, ignore_errors=True)
    shutil.copytree(os.path.join(H, cfg['webDir']), pub)
    for name in ('cordova.js', 'cordova_plugins.js'):  # no Cordova plugins: Capacitor still expects both, empty
        write(os.path.join(pub, name), '')
    write(os.path.join(MAIN, 'assets', 'capacitor.config.json'), json.dumps(cfg, indent='\t') + '\n')
    write(os.path.join(MAIN, 'assets', 'capacitor.plugins.json'), json.dumps(PLUGINS, indent='\t') + '\n')
    write(os.path.join(MAIN, 'res', 'xml', 'config.xml'), CONFIG_XML)
    mod = os.path.join(A, 'capacitor-cordova-android-plugins')
    write(os.path.join(mod, 'build.gradle'), CORDOVA_BUILD)
    write(os.path.join(mod, 'cordova.variables.gradle'), CORDOVA_VARIABLES)
    write(os.path.join(mod, 'src', 'main', 'AndroidManifest.xml'), CORDOVA_MANIFEST)
    write(os.path.join(mod, 'src', 'main', 'java', '.gitkeep'), '')
    write(os.path.join(mod, 'src', 'main', 'res', '.gitkeep'), '\n')
    print('android/app/src/main/assets/public', sum(len(fs) for _, _, fs in os.walk(pub)), 'files')


if __name__ == '__main__':
    main()
